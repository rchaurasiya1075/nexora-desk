export type AssetClass =
  | "forex"
  | "crypto"
  | "metals"
  | "indices"
  | "energy"
  | "shares";

export type Instrument = {
  symbol: string;
  display: string;
  name: string;
  assetClass: AssetClass;
  /** Mid price seed, late Sep 2026. */
  base: number;
  digits: number;
  pip: number;
  /** Standard account bid/ask width in price units. */
  spreadStd: number;
  /** RAW account bid/ask width in price units. */
  spreadRaw: number;
  /** Contract size per 1.00 lot. */
  contractSize: number;
  leverage: number;
  /** Annualised-ish tick volatility for the simulator. */
  vol: number;
  /** Commission USD per 1.00 lot per side on RAW. 0 = spread-only. */
  commissionRaw: number;
  hours: string;
};

