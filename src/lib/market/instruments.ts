export const INSTRUMENT_MAP = new Map(INSTRUMENTS.map((i) => [i.symbol, i]));

export function getInstrument(symbol: string): Instrument {
  const inst = INSTRUMENT_MAP.get(symbol);
  if (!inst) throw new Error(`Unknown symbol ${symbol}`);
  return inst;
}

